  let lang = 'tr';
  let names = [];

  function ordinal(n) {
    const v = Number(n);
    const mod = v % 100;
    if (mod >= 11 && mod <= 13) return 'th';
    switch (v % 10) {
      case 1: return 'st';
      case 2: return 'nd';
      case 3: return 'rd';
      default: return 'th';
    }
  }

  function fill(text, vars) {
    if (!vars) return text;
    return String(text).replace(/\{(\w+)\}/g, function (_, key) {
      return vars[key] == null ? '' : String(vars[key]);
    });
  }

  function nameOf(label) {
    const raw = String(label || '');
    for (let i = 0; i < names.length; i++) {
      if (names[i].tr === raw) return names[i].en;
    }
    if (PHRASES[raw]) return PHRASES[raw];
    return raw;
  }

  function addNames(list) {
    (list || []).forEach(function (row) {
      if (!row || !row.tr || !row.en) return;
      names.push({ tr: row.tr, en: row.en });
    });
    names.sort(function (a, b) { return b.tr.length - a.tr.length; });
  }

  function t(key, vars) {
    const table = STR[lang] || STR.tr;
    const text = table[key] != null ? table[key] : (STR.tr[key] != null ? STR.tr[key] : key);
    return fill(text, vars);
  }

  function has(key) {
    return STR.tr[key] != null;
  }

  function say(text) {
    const raw = text == null ? '' : String(text);
    if (lang !== 'en' || !raw) return raw;
    if (PHRASES[raw]) return PHRASES[raw];
    for (let i = 0; i < RULES.length; i++) {
      const m = RULES[i].re.exec(raw);
      if (m) return RULES[i].to(m);
    }
    let s = raw;
    for (let i = 0; i < names.length; i++) {
      if (s.indexOf(names[i].tr) >= 0) s = s.split(names[i].tr).join(names[i].en);
    }
    if (PHRASES[s]) return PHRASES[s];
    return s;
  }

  function setLang(next) {
    lang = next === 'en' ? 'en' : 'tr';
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = lang;
    }
    return lang;
  }

  function getLang() { return lang; }

  function clubName(club) {
    if (!club) return '';
    return lang === 'en' && club.nameEn ? club.nameEn : club.name;
  }

  function clubShort(club) {
    if (!club) return '';
    return lang === 'en' && club.shortEn ? club.shortEn : club.short;
  }

  function itemName(item) {
    if (!item) return '';
    const key = 'item.' + item.id;
    return has(key) ? t(key) : item.name;
  }

  function itemBlurb(item) {
    if (!item) return '';
    const key = 'item.' + item.id + '.blurb';
    return has(key) ? t(key) : item.blurb;
  }

  return {
    t: t,
    has: has,
    say: say,
    setLang: setLang,
    getLang: getLang,
    lang: getLang,
    addNames: addNames,
    clubName: clubName,
    clubShort: clubShort,
    itemName: itemName,
    itemBlurb: itemBlurb,
    STR: STR,
  };
